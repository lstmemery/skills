import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


PACKAGE = Path(__file__).resolve().parents[1]
SCRIPT = PACKAGE / "scripts/worker-records.py"


class JailBriefPreflightTest(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.bundle = self.root / "bundle"
        self.bundle.mkdir()
        for relative in (
            "production/spec.md",
            "tests/test_contract.py",
            "fixtures/sample.json",
            "prior/previous-report.md",
        ):
            path = self.bundle / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("supplied input\n", encoding="utf-8")

    def make_brief(self, **overrides):
        inventory = {
            "schema": 1,
            "artifact_paths": ["report.md", "result-record.json"],
            "production_inputs": ["production/spec.md"],
            "test_inputs": ["tests/test_contract.py"],
            "fixture_inputs": ["fixtures/sample.json"],
            "prior_inputs": ["prior/previous-report.md"],
        }
        inventory.update(overrides)
        brief = self.root / "brief.md"
        brief.write_text(
            "# Jailed task\n\n"
            "## Jail pre-launch inventory\n\n"
            "```json jail-preflight\n"
            + json.dumps(inventory, indent=2)
            + "\n```\n",
            encoding="utf-8",
        )
        return brief

    def call(self, brief):
        return subprocess.run(
            [
                sys.executable,
                "-B",
                str(SCRIPT),
                "check-brief",
                "--jail",
                "--bundle-root",
                str(self.bundle),
                str(brief),
            ],
            capture_output=True,
            text=True,
            cwd=self.root,
            timeout=5,
        )

    def test_check_brief_accepts_complete_jail_inventory_and_bundle(self):
        process = self.call(self.make_brief())

        self.assertEqual(process.returncode, 0, process.stderr)
        self.assertIn("BRIEF OK:", process.stdout)

    def test_check_brief_rejects_artifacts_that_are_not_flat_import_filenames(self):
        process = self.call(self.make_brief(artifact_paths=["reports/report.md"]))

        self.assertEqual(process.returncode, 1)
        self.assertIn("invalid declared artifact path 'reports/report.md'", process.stderr)
        self.assertIn("single filenames directly under the workspace root", process.stderr)

    def test_check_brief_reports_missing_production_input_before_launch(self):
        process = self.call(
            self.make_brief(production_inputs=["production/missing-spec.md"])
        )

        self.assertEqual(process.returncode, 1)
        self.assertIn("missing production input in bundle: production/missing-spec.md", process.stderr)

    def test_check_brief_reports_missing_test_input_before_launch(self):
        process = self.call(self.make_brief(test_inputs=["tests/missing_test.py"]))

        self.assertEqual(process.returncode, 1)
        self.assertIn("missing test input in bundle: tests/missing_test.py", process.stderr)

    def test_check_brief_reports_missing_fixture_and_prior_inputs_before_launch(self):
        process = self.call(self.make_brief(
            fixture_inputs=["fixtures/missing.json"],
            prior_inputs=["prior/missing-report.md"],
        ))

        self.assertEqual(process.returncode, 1)
        self.assertIn("missing fixture input in bundle: fixtures/missing.json", process.stderr)
        self.assertIn("missing prior input in bundle: prior/missing-report.md", process.stderr)

    def test_jail_template_copies_worker_schema_and_has_a_valid_import_declaration(self):
        template = PACKAGE / "templates/jail-task-brief.md"
        content = template.read_text(encoding="utf-8")
        schema_process = subprocess.run(
            [sys.executable, "-B", str(SCRIPT), "schema", "--format", "md"],
            capture_output=True,
            text=True,
            timeout=5,
        )

        self.assertEqual(schema_process.returncode, 0, schema_process.stderr)
        self.assertIn(schema_process.stdout.rstrip(), content)
        worker_schema_title = (
            "## Worker result record (generated by "
            "`worker-records.py schema --format md`)"
        )
        self.assertEqual(content.count(worker_schema_title), 1)
        self.assertIn("Jail import declaration", content)
        self.assertIn("`tools/pii-jail/stage-run-artifacts.py`", content)
        start = content.index("<!-- jail-import-example:start -->")
        end = content.index("<!-- jail-import-example:end -->")
        example_text = content[start:end]
        example = json.loads(example_text.split("```json", 1)[1].split("```", 1)[0])
        self.assertEqual(set(example), {"schema", "artifacts"})
        self.assertEqual(example["schema"], 1)
        self.assertEqual(set(example["artifacts"][0]), {"path", "sha256"})
        self.assertEqual(example["artifacts"][0]["path"], "example-report.md")
        self.assertEqual(
            example["artifacts"][0]["sha256"],
            "445e0234ea41ef75a7da9d144a64abac0d09bee7e206dd2386cb68c6a84f531c",
        )


if __name__ == "__main__":
    unittest.main()
