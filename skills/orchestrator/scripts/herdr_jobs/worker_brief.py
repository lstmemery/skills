"""Validate structured worker-brief declarations against their assignment.

A structured brief carries exactly one fenced ``json worker-brief`` block.
The block is the brief core: identity, repository binding, working directory,
and path scope live there and nowhere else in the brief. The launch boundary
compares the block with the coordinator's machine-readable assignment and
refuses copied identities, mismatched repositories or paths, and leftover or
duplicated instructions. Ambiguity is a failure, never a guess.
"""

import json
from pathlib import Path
import re

from .records import (DEFAULT_PROTECTED_PATHS, WORKER_MODES, is_branch_name, is_commit_id,
                      paths_overlap)


DECLARATION_INFO = "json worker-brief"
DECLARATION_SCHEMA = 1
DECLARATION_FIELDS = (
    "schema",
    "task_id",
    "assignment_revision",
    "worker_mode",
    "objective",
    "cwd",
    "output_directory",
    "repository",
    "scope",
    "authority",
    "required_context",
    "done_checks",
    "recovery",
    "stop_rules",
    "outcome",
    "result_schema",
    "output_redaction",
)
REPOSITORY_FIELDS = ("repo", "worktree", "branch", "base")
SCOPE_FIELDS = ("readable", "editable", "protected")
CONTEXT_FIELDS = ("path", "purpose")
CONTEXT_OPTIONAL_FIELDS = ("kind",)
MANAGED_OUTPUT = "managed"
MAX_REVISION = 2**63 - 1
MAX_TEXT = 100000
MAX_PATHS = 128
# Identity, repository, and path fields belong only in the declaration. A
# restatement elsewhere is a copied leftover or a second source of truth.
DECLARED_KEYS = (
    "task_id", "assignment_revision", "worker_mode", "cwd", "worktree", "branch",
    "base", "base_commit", "repo", "repository", "candidate_branch",
    "output_directory", "editable_paths", "protected_paths", "scope",
    "scope.readable", "scope.editable", "scope.protected",
)
KEY_RESTATEMENT = re.compile(
    r"^ {0,3}(?:[-*+]\s+)?(?:\*\*|__)?(?P<key>" + "|".join(re.escape(key) for key in DECLARED_KEYS)
    + r")(?:\*\*|__)?\s*:(?:\*\*|__)?",
    re.IGNORECASE,
)
# Signals that a task is a worker brief and therefore needs a declaration.
BRIEF_CORE_LINE = re.compile(r"^\s*(?:task_id|assignment_revision)\s*:", re.IGNORECASE | re.MULTILINE)
RESULT_RECORD_HEADING = "## Worker result record (generated by `worker-records.py schema --format md`)"
PLACEHOLDERS = (re.compile(r"\{\{[^{}\n]*\}\}"), re.compile(r"\bEXACT_ATTEMPT_ID\b"))
HEADING = re.compile(r"^ {0,3}(#{1,6})\s+(.+?)\s*#*\s*$")
DUPLICATE_LINE_MINIMUM = 40


class BriefLines:
    """Classify brief lines by CommonMark fence membership.

    A fence closes only with its opening character and at least its opening
    length; an unclosed fence extends through the end of the document.
    """

    def __init__(self, content):
        self.declarations = []
        self.prose = []
        self.other_fenced = []
        fence = None
        for number, line in enumerate(content.splitlines(), 1):
            if fence is None:
                opening = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", line)
                if opening and (opening.group(1)[0] == "~" or "`" not in opening.group(2)):
                    marker, info = opening.groups()
                    fence = {"char": marker[0], "length": len(marker),
                             "info": " ".join(info.split()), "line": number, "body": []}
                    continue
                self.prose.append((number, line))
                continue
            closing = re.match(r"^ {0,3}([`~]+)[ \t]*$", line)
            if (closing and closing.group(1)[0] == fence["char"]
                    and len(closing.group(1)) >= fence["length"]
                    and len(set(closing.group(1))) == 1):
                self._close(fence, closed=True)
                fence = None
                continue
            fence["body"].append((number, line))
        if fence is not None:
            self._close(fence, closed=False)

    def _close(self, fence, closed):
        if fence["info"] == DECLARATION_INFO:
            self.declarations.append({"line": fence["line"], "closed": closed,
                                      "text": "\n".join(line for _, line in fence["body"])})
        else:
            self.other_fenced.extend(fence["body"])


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def _text(value):
    return isinstance(value, str) and bool(value.strip()) and "\0" not in value and len(value) <= MAX_TEXT


def _exact_fields(value, required, optional, label, issues):
    if not isinstance(value, dict):
        issues.append(f"{label} must be an object")
        return False
    missing = [key for key in required if key not in value]
    unknown = sorted(set(value) - set(required) - set(optional))
    if missing:
        issues.append(f"{label} is missing required field(s): {', '.join(missing)}")
    if unknown:
        issues.append(f"{label} has unknown field(s): {', '.join(unknown)}")
    return not missing and not unknown


def _path_array(value, label, issues, require_nonempty=False):
    if not isinstance(value, list) or len(value) > MAX_PATHS:
        issues.append(f"{label} must be an array of at most {MAX_PATHS} paths")
        return []
    if require_nonempty and not value:
        issues.append(f"{label} must not be empty")
    paths = []
    for index, item in enumerate(value):
        if not _text(item) or len(item) > 4096:
            issues.append(f"{label}[{index}] must be a non-empty path string")
        else:
            paths.append(item)
    if len(set(paths)) != len(paths):
        issues.append(f"{label} must not contain duplicate paths")
    return paths


def validate_declaration(declaration):
    """Return schema issues for one parsed declaration object."""
    issues = []
    if not _exact_fields(declaration, DECLARATION_FIELDS, (), "worker-brief declaration", issues):
        return issues
    if type(declaration["schema"]) is not int or declaration["schema"] != DECLARATION_SCHEMA:
        issues.append(f"worker-brief declaration schema must be {DECLARATION_SCHEMA}")
    if not _text(declaration["task_id"]) or len(declaration["task_id"]) > 200:
        issues.append("task_id must be a non-empty string of at most 200 characters")
    revision = declaration["assignment_revision"]
    if type(revision) is not int or not 1 <= revision <= MAX_REVISION:
        issues.append(f"assignment_revision must be an integer from 1 to {MAX_REVISION}")
    if not isinstance(declaration["worker_mode"], str) or declaration["worker_mode"] not in WORKER_MODES:
        issues.append("worker_mode must be literal or inferential")
    for key in ("objective", "authority", "recovery", "stop_rules", "outcome",
                "result_schema", "output_redaction"):
        if not _text(declaration[key]):
            issues.append(f"{key} must be a non-empty string")
    if not _text(declaration["cwd"]) or not Path(declaration["cwd"]).is_absolute():
        issues.append("cwd must be an absolute path")
    output = declaration["output_directory"]
    if output != MANAGED_OUTPUT and (not _text(output) or not Path(output).is_absolute()):
        issues.append(f"output_directory must be an absolute path or {MANAGED_OUTPUT!r}")

    repository = declaration["repository"]
    if repository is not None and _exact_fields(
            repository, REPOSITORY_FIELDS, (), "repository", issues):
        for key in ("repo", "worktree"):
            if not _text(repository[key]) or not Path(repository[key]).is_absolute():
                issues.append(f"repository.{key} must be an absolute path")
        if not is_branch_name(repository["branch"]):
            issues.append("repository.branch must be a plain Git branch name")
        if not isinstance(repository["base"], str) or not is_commit_id(repository["base"]):
            issues.append("repository.base must be a full Git commit ID")

    scope = declaration["scope"]
    if _exact_fields(scope, SCOPE_FIELDS, (), "scope", issues):
        _path_array(scope["readable"], "scope.readable", issues)
        _path_array(scope["editable"], "scope.editable", issues)
        protected = _path_array(scope["protected"], "scope.protected", issues, require_nonempty=True)
        missing = [path for path in DEFAULT_PROTECTED_PATHS if path not in protected]
        if missing:
            issues.append(f"scope.protected is missing default protected path(s): {', '.join(missing)}")

    context = declaration["required_context"]
    if not isinstance(context, list) or len(context) > MAX_PATHS:
        issues.append(f"required_context must be an array of at most {MAX_PATHS} entries")
    else:
        for index, entry in enumerate(context):
            label = f"required_context[{index}]"
            if _exact_fields(entry, CONTEXT_FIELDS, CONTEXT_OPTIONAL_FIELDS, label, issues):
                for key in entry:
                    if not _text(entry[key]):
                        issues.append(f"{label}.{key} must be a non-empty string")

    checks = declaration["done_checks"]
    if not isinstance(checks, list) or not checks or not all(_text(item) for item in checks):
        issues.append("done_checks must be a non-empty array of non-empty strings")
    return issues


def _leftover_issues(lines):
    issues = []
    for number, line in lines.prose + lines.other_fenced:
        match = KEY_RESTATEMENT.match(line)
        if match:
            issues.append(
                f"line {number} restates {match.group('key')!r} outside the worker-brief "
                "declaration; keep identity, repository, and paths only in the declaration")
    seen_lines = {}
    seen_headings = {}
    for number, line in lines.prose:
        heading = HEADING.match(line)
        if heading:
            key = (len(heading.group(1)), heading.group(2).casefold())
            seen_headings.setdefault(key, []).append(number)
            continue
        normalized = " ".join(line.split()).casefold()
        if len(normalized) >= DUPLICATE_LINE_MINIMUM:
            seen_lines.setdefault(normalized, []).append(number)
    for (_, title), numbers in seen_headings.items():
        if len(numbers) > 1:
            issues.append(f"duplicate section heading {title!r} at lines "
                          f"{', '.join(map(str, numbers))}; remove the leftover copy")
    for numbers in seen_lines.values():
        if len(numbers) > 1:
            issues.append(f"duplicate instruction at lines {', '.join(map(str, numbers))}; "
                          "remove the leftover copy")
    return issues


def parse(content):
    """Return ``(declaration, issues)``; declaration is None when absent or invalid."""
    issues = []
    for pattern in PLACEHOLDERS:
        for match in pattern.finditer(content):
            line = content.count("\n", 0, match.start()) + 1
            issues.append(f"line {line} has an unreplaced template placeholder {match.group(0)!r}")
    lines = BriefLines(content)
    if not lines.declarations:
        return None, issues + ["brief has no ```json worker-brief declaration block"]
    if len(lines.declarations) > 1:
        starts = ", ".join(str(block["line"]) for block in lines.declarations)
        return None, issues + [f"brief has duplicate worker-brief declaration blocks at lines {starts}"]
    block = lines.declarations[0]
    if not block["closed"]:
        issues.append(f"worker-brief declaration at line {block['line']} is not closed")
    issues.extend(_leftover_issues(lines))
    try:
        declaration = json.loads(block["text"], object_pairs_hook=_unique_object)
    except (json.JSONDecodeError, ValueError) as error:
        return None, issues + [f"worker-brief declaration is not valid JSON: {error}"]
    schema_issues = validate_declaration(declaration)
    if schema_issues:
        return None, issues + schema_issues
    return declaration, issues


def is_structured_brief(content):
    """Whether task text looks like a worker brief and so must carry a declaration."""
    if BriefLines(content).declarations:
        return True
    return bool(BRIEF_CORE_LINE.search(content)) or RESULT_RECORD_HEADING in content


def _canonical(value, base=None):
    path = Path(str(value)).expanduser()
    if base is not None and not path.is_absolute():
        path = Path(base) / path
    try:
        return path.resolve(strict=False)
    except (OSError, RuntimeError):
        return None


def _same_path(declared, assigned, base=None):
    left, right = _canonical(declared, base), _canonical(assigned, base)
    return left is not None and left == right


def assignment_issues(declaration, assignment):
    """Compare a valid declaration with the coordinator's assignment record."""
    issues = []
    if declaration["task_id"] != assignment["task_id"]:
        issues.append(f"task_id {declaration['task_id']!r} does not match assignment "
                      f"{assignment['task_id']!r}")
    if declaration["assignment_revision"] != assignment["assignment_revision"]:
        issues.append(f"assignment_revision {declaration['assignment_revision']} does not match "
                      f"assignment {assignment['assignment_revision']}")
    if declaration["worker_mode"] != assignment["worker_mode"]:
        issues.append(f"worker_mode {declaration['worker_mode']!r} does not match assignment "
                      f"{assignment['worker_mode']!r}")
    cwd = assignment["cwd"]
    if not _same_path(declaration["cwd"], cwd):
        issues.append(f"cwd {declaration['cwd']!r} does not match assignment {cwd!r}")
    output = assignment["output_directory"]
    if (declaration["output_directory"] == MANAGED_OUTPUT) != (output == MANAGED_OUTPUT) or (
            output != MANAGED_OUTPUT and not _same_path(declaration["output_directory"], output)):
        issues.append(f"output_directory {declaration['output_directory']!r} does not match "
                      f"assignment {output!r}")

    repository = declaration["repository"]
    worktree = assignment["repository_worktree"]
    if worktree is None:
        if repository is not None:
            issues.append("repository is declared but the assignment does not write a repository")
    elif repository is None:
        issues.append("repository must be declared for a repository-writing assignment")
    else:
        for declared_key, assigned_key in (("worktree", "path"), ("repo", "repo_root")):
            if not _same_path(repository[declared_key], worktree[assigned_key]):
                issues.append(f"repository.{declared_key} {repository[declared_key]!r} does not match "
                              f"assignment {worktree[assigned_key]!r}")
        if repository["base"].lower() != worktree["base_commit"].lower():
            issues.append(f"repository.base {repository['base']!r} does not match assignment "
                          f"{worktree['base_commit']!r}")
        branch = assignment["candidate_branch"]
        if branch is None:
            issues.append("assignment does not record candidate_branch; the declared branch "
                          "cannot be verified")
        elif repository["branch"] != branch:
            issues.append(f"repository.branch {repository['branch']!r} does not match assignment "
                          f"{branch!r}")

    scope = declaration["scope"]
    declared_editable = {_canonical(path, cwd) for path in scope["editable"]}
    assigned_editable = {_canonical(path, cwd) for path in assignment["editable_paths"]}
    if None in declared_editable or declared_editable != assigned_editable:
        issues.append(f"scope.editable {scope['editable']!r} does not match assignment "
                      f"editable_paths {list(assignment['editable_paths'])!r}")
    for protected in assignment["protected_paths"]:
        if not any(_same_path(path, protected, cwd) for path in scope["protected"]):
            issues.append(f"scope.protected omits assigned protected path {protected!r}")
    for editable in scope["editable"]:
        if any(paths_overlap(editable, protected, base=cwd) for protected in scope["protected"]):
            issues.append(f"scope.editable path is protected: {editable}")
    return issues


def brief_issues(content, assignment=None):
    """Parse a brief and, when given, compare it with its assignment record."""
    declaration, issues = parse(content)
    if declaration is not None and assignment is not None:
        issues.extend(assignment_issues(declaration, assignment))
    return declaration, issues


def assignment_from_job(job):
    """Project a prepared managed job onto the fields its brief must match."""
    identity = job.get("worker_result") or {"task_id": job["job_id"], "assignment_revision": 1}
    return {
        "task_id": identity["task_id"],
        "assignment_revision": identity["assignment_revision"],
        "worker_mode": job["worker_mode"],
        "cwd": job["cwd"],
        # The helper assigns each managed attempt's output directory at launch.
        "output_directory": MANAGED_OUTPUT,
        "repository_worktree": job["repository_worktree"] if job["writes_repository"] else None,
        "candidate_branch": job.get("candidate_branch"),
        "editable_paths": job["editable_paths"],
        "protected_paths": job["protected_paths"],
    }


def requires_declaration(job):
    """Whether the assignment itself demands a structured brief.

    ``structured_brief: true`` opts a job in; ``candidate_branch`` exists only to
    verify a declared branch, so it implies the same. The brief text cannot
    lift either requirement, so a copied prose brief fails closed.
    """
    return job.get("structured_brief") is True or "candidate_branch" in job


def job_brief_errors(job):
    """Launch-boundary check: a structured brief must match its manifest job.

    Legacy prose tasks on assignments that do not require a declaration are
    exempt; see "Pre-launch brief validation" in references/workers.md.
    """
    if "review_of" in job:
        return []
    required = requires_declaration(job)
    if not required and not is_structured_brief(job.get("task", "")):
        return []
    declaration, issues = brief_issues(job.get("task", ""), assignment_from_job(job))
    if declaration is None and required:
        issues.append("the assignment requires a structured brief (structured_brief or "
                      "candidate_branch); prose task text cannot satisfy it")
    return issues
